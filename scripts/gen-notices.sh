#!/bin/bash
# Regenerate THIRD_PARTY_NOTICES.md. Needs network (npm registry + unpkg) for license texts.
# Verified = version and license read from a header inside vendor/. Everything else is marked unverified:
# mermaid.min.js bundles its dependencies without per-package headers, so their versions are not recoverable from vendor/.
set -euo pipefail
cd "$(dirname "$0")/.."
OUT=THIRD_PARTY_NOTICES.md
T=$(mktemp -d); trap 'rm -rf "$T"' EXIT

hdr() { grep -m1 -o "$1" "$2" || { echo "vendor header not found: $1" >&2; exit 1; }; }
MARKED=$(hdr 'marked v[0-9.]*' vendor/marked.min.js | cut -d' ' -f2 | tr -d v)
MERMAID=$(hdr 'version:"12\.[0-9.]*"' vendor/mermaid.min.js | cut -d'"' -f2)
PURIFY=$(hdr 'DOMPurify [0-9][0-9.]*' vendor/mermaid.min.js | cut -d' ' -f2)
LODASH=$(hdr 'lodash#[0-9][0-9.]*' vendor/mermaid.min.js | cut -d'#' -f2)
hdr 'Copyright (c) 2011-2025, Christopher Jeffrey. (MIT Licensed)' vendor/marked.min.js >/dev/null
hdr 'Released under the Apache license 2.0 and Mozilla Public License 2.0' vendor/mermaid.min.js >/dev/null
hdr 'Released under MIT license <https://lodash.com/license>' vendor/mermaid.min.js >/dev/null

# name|version|license|copyright holder|declared range|status
{
echo "marked|$MARKED|MIT|MarkedJS (2018+) and Christopher Jeffrey (2011-2018; header says 2011-2025)||verified: version, license and holder in vendor/marked.min.js header; full text from npm"
echo "mermaid|$MERMAID|MIT|||verified: version in vendor/mermaid.min.js; license from npm package (no header in the bundle)"
echo "dompurify|$PURIFY|MPL-2.0 OR Apache-2.0|Cure53 and other contributors||verified: version and license in vendor/mermaid.min.js bundled-license block"
echo "lodash-es|$LODASH|MIT|OpenJS Foundation and other contributors||verified: version and license in vendor/mermaid.min.js bundled-license block (also embeds Underscore.js 1.8.3 parts, Jeremy Ashkenas, DocumentCloud and Investigative Reporters & Editors, MIT)"
# Dependency ranges copied from mermaid@12.1.0 package.json (https://unpkg.com/mermaid@12.1.0/package.json)
for p in cytoscape@^3.34.0 cytoscape-cose-bilkent@^4.1.0 cytoscape-fcose@^2.2.0 d3@^7.9.0 d3-sankey@^0.12.3 dagre-d3-es@7.0.14 dayjs@^1.11.21 elkjs@^0.9.3 es-toolkit@^1.45.1 katex@^0.16.47 khroma@^2.1.0 roughjs@^4.6.6 stylis@^4.3.6 ts-dedent@^2.2.0 uuid@^11.1.0 chevrotain@~13.2.0 @braintree/sanitize-url@^7.1.2 @iconify/utils@^3.0.2 @upsetjs/venn.js@^2.0.0 @mermaid-js/parser@^2.0.1; do
  echo "${p%@*}||||${p##*@}|unverified: bundled by mermaid $MERMAID; exact bundled version not recoverable from vendor/, license read from the highest release inside mermaid's declared range"
done
} > "$T/list"

{
echo "# Third-party notices"
echo
echo "Glimpse bundles the libraries below (vendor/). Generated by scripts/gen-notices.sh; do not edit by hand."
echo "Glimpse itself is MIT licensed (see LICENSE). Entries marked unverified could not be confirmed from a file in vendor/."
echo
echo "Also embedded in the cytoscape portion of the mermaid bundle (headers present in vendor/mermaid.min.js, MIT): Promises/A+ Thenable (Ralf S. Engelschall), jQuery-style event object (jQuery Foundation), Bezier curve generator (Gaetan Renaudeau), Runge-Kutta spring physics (Koen Bok, adapted from Framer.js)."
echo
while IFS='|' read -r name ver lic holder range status; do
  if [ -n "$ver" ]; then q=$ver; else q=$range; fi
  j=$(curl -fsSL "https://unpkg.com/$name@$q/package.json" || true)
  [ -n "$j" ] || { echo "package.json fetch failed: $name@$q" >&2; exit 1; }
  read -r rver rlic rauthor < <(printf '%s' "$j" | python3 -I -c 'import sys,json;d=json.load(sys.stdin);l=d.get("license");l=l if isinstance(l,str) else (l or {}).get("type","");a=d.get("author");a=a if isinstance(a,str) else (a or {}).get("name","");print(d["version"].replace(" ","_"),(l or "?").replace(" ","_"),(a or "-").replace(" ","_"))')
  [ -n "$ver" ] || ver="$rver (highest match for $range, unverified for bundle)"
  [ -n "$lic" ] || lic="${rlic//_/ }"
  text=""
  for f in LICENSE LICENSE.md LICENSE.txt license LICENCE; do
    text=$(curl -fsSL "https://unpkg.com/$name@$rver/$f" 2>/dev/null) && break || text=""
  done
  [ -n "$text" ] || text="(license file not found on unpkg: unverified)"
  case "$lic:$text" in "?:The MIT License"*) lic="MIT (from LICENSE file; package.json has no license field)";; esac
  echo "## $name"
  echo
  echo "- Version: $ver"
  echo "- License: $lic"
  echo "- Copyright holder: ${holder:-see license text below (npm author: ${rauthor//_/ })}"
  echo "- Status: $status"
  echo
  echo '```text'
  printf '%s\n' "$text"
  echo '```'
  echo
done < "$T/list"
} > "$OUT"
echo "wrote $OUT"
